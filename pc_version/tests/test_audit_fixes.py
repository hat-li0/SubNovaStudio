def test_video_extractor_image_based_and_sdh_protection():
    """Verify that bitmap image subtitles are identified and blocked, and SDH tracks are penalized."""
    from app.subtitle.video_extractor import SubtitleStreamInfo, VideoSubtitleExtractor

    streams = [
        SubtitleStreamInfo(index=0, global_index=2, codec_name="hdmv_pgs_subtitle", extension=".sup", language="eng", title="English PGS", is_image_based=True),
        SubtitleStreamInfo(index=1, global_index=3, codec_name="subrip", extension=".srt", language="eng", title="English [SDH]", is_hearing_impaired=True, frame_count=350),
        SubtitleStreamInfo(index=2, global_index=4, codec_name="ass", extension=".ass", language="eng", title="English Dialogue", frame_count=350, is_default=True),
    ]

    best = VideoSubtitleExtractor.select_best_stream(streams, "en")
    assert best is not None
    # Must select ASS dialogue track over SDH and PGS!
    assert best.index == 2
    assert "Dialogue" in best.title

    # Must block extraction on image-based stream
    with tempfile.NamedTemporaryFile(suffix=".mkv", delete=False) as tmp:
        v_path = tmp.name

    try:
        from unittest.mock import patch
        with patch.object(VideoSubtitleExtractor, "probe_subtitle_streams", return_value=streams):
            ok, _, err = VideoSubtitleExtractor.extract_subtitle(v_path, stream_index=0)
            assert ok is False
            assert "ترجمة صورية" in err
    finally:
        if os.path.exists(v_path):
            try:
                os.remove(v_path)
            except Exception:
                pass

