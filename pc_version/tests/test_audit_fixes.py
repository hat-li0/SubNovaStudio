def test_database_thread_local_and_indexes():
    """Verify DatabaseManager reuses connections per thread, closes cleanly, and creates indexes."""
    with tempfile.NamedTemporaryFile(suffix=".db", delete=False) as tmp:
        db_path = tmp.name

    try:
        db = DatabaseManager(db_path=db_path)
        conn1 = db.get_connection()
        conn2 = db.get_connection()
        # Connection should be reused in the same thread
        assert conn1 is conn2

        # Check indexes exist
        rows = db.fetch_all("SELECT name FROM sqlite_master WHERE type='index'")
        idx_names = [r["name"] for r in rows]
        assert "idx_tm_lookup" in idx_names
        assert "idx_characters_anime" in idx_names
        assert "idx_glossary_anime" in idx_names

        # Clean close
        db.close()
    finally:
        if os.path.exists(db_path):
            try:
                os.remove(db_path)
            except Exception:
                pass

def test_srt_writer_cross_format_conversion():
    """Verify ASS time and linebreaks are correctly adapted for standard SRT."""
    doc = SubtitleDocument(format=SubtitleFormat.ASS)
    doc.events.append(
        SubtitleEvent(
            id=1,
            start_time="0:01:23.45",
            end_time="0:01:25.80",
            original_text=r"{\an8\pos(100,200)}مرحباً بك\Nيا صديقي",
            translated_text=r"{\an8\pos(100,200)}مرحباً بك\Nيا صديقي"
        )
    )

    writer = SRTWriter()
    content = writer.write_text(doc)

    # Must format time to 00:01:23,450 --> 00:01:25,800
    assert "00:01:23,450 --> 00:01:25,800" in content
    # Must strip raw ASS tags like {\an8\pos(100,200)}
    assert "{\\an8" not in content
    assert "\\pos" not in content
    # Must convert \N to newline
    assert "مرحباً بك\nيا صديقي" in content

