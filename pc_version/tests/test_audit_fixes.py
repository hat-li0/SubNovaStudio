def test_healer_dual_dialogue_dash_restoration():
    """Verify that when original had multi-speaker dashes and translation dropped one, it is restored."""
    from app.quality.healer import SubtitleHealer

    orig = r"- Are you ready?\N- Yes, let's go!"
    # LLM dropped second dash
    draft = r"- هل أنت مستعد؟\Nأجل، لننطلق!"
    healed = SubtitleHealer.heal(draft, original_text=orig)
    assert healed == r"- هل أنت مستعد؟\N- أجل، لننطلق!"

    # Single speaker with hallucinated dash should have dash removed
    single_orig = "I am ready."
    single_draft = "- أنا مستعد."
    single_healed = SubtitleHealer.heal(single_draft, original_text=single_orig)
    assert single_healed == "أنا مستعد."


