def test_purify_extracted_subtitle_full():
    """Verify that purify_extracted_subtitle cleans Aegisub garbage, ghost lines, and sets 1080p PlayRes."""
    with tempfile.NamedTemporaryFile(suffix=".ass", delete=False) as tmp:
        sub_path = tmp.name

